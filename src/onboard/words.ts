const fmt = (n: number): string => n.toLocaleString("en-US");

export const size = (bytes: number): string => {
  if (bytes < 1_000_000) return `${Math.max(1, Math.round(bytes / 1000))} KB`;
  if (bytes < 1e9) return `${(bytes / 1e6).toFixed(bytes < 1e7 ? 1 : 0)} MB`;
  return `${(bytes / 1e9).toFixed(1)} GB`;
};

export const filesLine = (notes: number, others: number, bytes: number): string => {
  const note = notes === 1 ? "note" : "notes";
  const file = others === 1 ? "file" : "files";
  if (notes > 0 && others > 0) return `${fmt(notes)} ${note} and ${fmt(others)} other ${file} (${size(bytes)})`;
  if (others === 0 && notes > 0) return `${fmt(notes)} ${note} (${size(bytes)})`;
  if (notes === 0 && others > 0) return `${fmt(others)} ${file} (${size(bytes)})`;
  return "Nothing in this vault yet";
};

